import assert from 'node:assert/strict';
export async function checkCommentNavigation({cdp,evaluate,wait,delay,request,app,head,previous}) {
  const diff = await request(`/api/diff?sha=${head}`);
  const oldDiff = await request(`/api/diff?sha=${previous}`);
  const add = (sha,file,body) => request('/api/comments','POST',{sha,anchor:{fileId:file.id,side:'new',startLine:2,endLine:2},body});
  const older = await add(previous,oldDiff.files.find(f=>f.path==='example.js'),'历史提交评论');
  const otherFile = await add(head,diff.files.find(f=>f.path==='navigation.txt'),'另一个文件评论');
  const newest = await add(head,diff.files.find(f=>f.path==='example.js'),'当前文件评论');
  await app.store.reply(newest.id,'回复内容\n'.repeat(35),'ai');
  const storedBefore = JSON.stringify(app.store.list());
  await cdp('Page.reload');
  await wait('document.querySelector(".monaco-editor")');
  await evaluate('document.querySelector("#toggle-comments").click();document.querySelector("#comment-scope").value="all";document.querySelector("#comment-scope").dispatchEvent(new Event("change"))');
  const badges=()=>evaluate('[...document.querySelectorAll(".comment-read-state")].map(n=>n.textContent)');
  const active=()=>evaluate('document.querySelector(".comment-current")?.dataset.commentId');
  const key=async extra=>{
    await cdp('Input.dispatchKeyEvent',{type:'keyDown',key:'j',code:'KeyJ',modifiers:1,windowsVirtualKeyCode:74,...extra});
    await cdp('Input.dispatchKeyEvent',{type:'keyUp',key:'j',code:'KeyJ',modifiers:1});
  };
  assert.deepEqual(await badges(),['未读','未读','未读'],'rendering expanded threads does not mark them read');
  await evaluate('document.querySelector("#next-comment").focus()');
  await key(); await wait(`document.querySelector('.comment-current')?.dataset.commentId === '${newest.id}'`);
  assert.deepEqual(await badges(),['已读','未读','未读']);
  await key(); await wait(`document.querySelector('.comment-current')?.dataset.commentId === '${otherFile.id}'`);
  assert.ok((await evaluate('document.querySelector(".file-title").textContent')).includes('navigation.txt'));
  await key(); await wait(`document.querySelector('.comment-current')?.dataset.commentId === '${older.id}'`);
  assert.ok((await evaluate('document.querySelector("#commit-detail").textContent')).includes(previous));
  await key(); assert.equal(await active(),older.id,'end of list does not wrap');
  assert.ok((await evaluate('document.querySelector("#notice").textContent')).includes('最后一条'));
  assert.equal(JSON.stringify(app.store.list()),storedBefore,'read and navigation state never writes review data');
  assert.equal(await evaluate('document.querySelector(".history [aria-current=true]").dataset.commitSha'),previous,'comment selects matching commit');
  await evaluate('document.querySelector("#branch").value="refs/heads/untracked";document.querySelector("#branch").dispatchEvent(new Event("change"))');
  await wait('document.querySelectorAll("#commits .commit").length === 0 && !document.querySelector(".monaco-editor")');
  await evaluate(`document.querySelector('[data-comment-id="${older.id}"] .comment-body-link').click()`);
  await wait(`document.querySelector('#comment-commit [aria-current=true]')?.dataset.commitSha === '${previous}'`);
  assert.equal(await evaluate('document.querySelector("#branch").value'),'refs/heads/untracked','comment jump does not change branch');
  assert.equal(await evaluate('document.querySelectorAll("#comment-commit input").length'),0,'supplementary commit is outside select-all scope');
  await evaluate('document.querySelector("#branch").value="HEAD";document.querySelector("#branch").dispatchEvent(new Event("change"))');
  await wait('document.querySelectorAll("#commits .commit").length === 2 && document.querySelector(".monaco-editor")');
  await evaluate(`document.querySelector('[data-comment-id="${older.id}"] .comment-body-link').click()`);
  await wait(`document.querySelector('#commits [aria-current=true]')?.dataset.commitSha === '${previous}'`);
  assert.equal(await evaluate('document.querySelector("#comment-commit").hidden'),true,'loaded commit does not get duplicated');

  // Input, dialog, repeat and modified shortcuts must not steal interaction.
  await evaluate('document.querySelector("#commit-search").focus()');await key();assert.equal(await active(),older.id);
  await evaluate('document.querySelector("#next-comment").focus()');await key({modifiers:3});assert.equal(await active(),older.id);
  await key({autoRepeat:true});assert.equal(await active(),older.id);
  await evaluate(`document.querySelector('[data-comment-id="${newest.id}"] .reply-comment').click();document.querySelector('#reply-body').value='回复草稿'`);
  await key();assert.equal(await evaluate('document.querySelector("#reply-body").value'),'回复草稿');
  assert.equal(await active(),newest.id);
  await evaluate('document.querySelector("#cancel-reply").click();document.querySelector("#refresh").click()');
  await wait('!document.querySelector("#refresh").disabled');
  assert.deepEqual(await badges(),['已读','已读','已读'],'toolbar refresh keeps read state');
  await app.store.reply(newest.id,'新追问','ai');
  await wait('document.querySelector(".comment-read-state").textContent === "未读"');
  assert.equal(await evaluate('document.querySelector("#unread-count").textContent'),'1 未读');
  await evaluate(`document.querySelector('[data-comment-id="${newest.id}"] .comment-body-link').click()`);
  await wait('document.querySelector(".comment-read-state").textContent === "已读"');
  // Opening code marker marks the same discussion; polling itself never marks it read.
  await app.store.reply(newest.id,'另一个新追问','ai');
  await wait('document.querySelector(".comment-read-state").textContent === "未读"');
  const codePoint=await evaluate('(() => {const r=document.querySelector(".editor.modified .review-comment-underline").getBoundingClientRect();return {x:r.x+15,y:r.y+r.height/2}})()');
  await cdp('Input.dispatchMouseEvent',{type:'mousePressed',...codePoint,button:'left',clickCount:1});
  await cdp('Input.dispatchMouseEvent',{type:'mouseReleased',...codePoint,button:'left',clickCount:1});
  await wait('document.querySelector(".comment-preview")?.hidden === false');
  assert.equal((await badges())[0],'已读');
  const beforeHide = JSON.stringify(app.store.list());
  const hideHead=()=>evaluate(`(()=>{const input=[...document.querySelectorAll('.commit-select')].find(n=>n.value==='${head}');input.click();document.querySelector('#hide-commits').click()})()`);
  await hideHead();
  await wait('document.querySelectorAll("#comments .comment-card").length === 1');
  assert.equal(await evaluate('document.querySelector("#comment-count").textContent'),'1');
  assert.equal(await evaluate('document.querySelectorAll(".comment-preview:not([hidden])").length'),0,'hiding closes associated code popup');
  assert.equal(await evaluate('document.querySelectorAll("#comments .reply-item").length'),0);
  await evaluate('document.querySelector("#next-comment").click()');
  await wait(`document.querySelector('.comment-current')?.dataset.commentId === '${older.id}'`);
  await evaluate('document.querySelector("#show-hidden").click()');
  await wait('document.querySelectorAll("#comments .comment-card").length === 2');
  assert.ok((await evaluate('document.querySelector("#comment-visibility").textContent')).includes('隐藏项模式'));
  assert.equal(await evaluate('document.querySelectorAll("#comments .reply-item").length'),3);
  await evaluate('document.querySelector("#select-commits").click();document.querySelector("#hide-commits").click()');
  await wait('document.querySelectorAll("#comments .comment-card").length === 0');
  assert.equal(await evaluate('document.querySelector("#next-comment").disabled'),true);
  await evaluate('document.querySelector("#show-hidden").click()');
  await wait('document.querySelectorAll("#comments .comment-card").length === 3');
  await hideHead();await wait('document.querySelectorAll("#comments .comment-card").length === 1');
  await evaluate('document.querySelector("#restore-commits").click()');
  await wait('document.querySelectorAll("#comments .comment-card").length === 3');
  assert.equal(JSON.stringify(app.store.list()),beforeHide,'repeated hide and restore preserves complete review data');
  assert.deepEqual(await badges(),['已读','已读','已读'],'hide and restore preserves read versions');
  await cdp('Page.reload');await wait('document.querySelector(".monaco-editor")');
  await evaluate('document.querySelector("#toggle-comments").click();document.querySelector("#comment-scope").value="all";document.querySelector("#comment-scope").dispatchEvent(new Event("change"))');
  assert.deepEqual(await badges(),['未读','未读','未读'],'full reload resets read state');
  await cdp('Emulation.setDeviceMetricsOverride',{width:390,height:844,deviceScaleFactor:1,mobile:true});
  await evaluate('document.querySelector("#next-comment").click()');
  await wait(`document.querySelector('.comment-current')?.dataset.commentId === '${newest.id}'`);
  assert.equal(await evaluate('document.documentElement.scrollWidth<=innerWidth'),true,'navigation and badges fit narrow screens');
  await cdp('Emulation.setDeviceMetricsOverride',{width:1600,height:1000,deviceScaleFactor:1,mobile:false});
  await delay(350);
  // A pending inline draft blocks shortcut navigation even when focus moves to code/toolbar.
  const gutter=await evaluate('(() => {const n=[...document.querySelectorAll(".editor.modified .line-numbers")].find(n=>n.textContent.trim()==="2"),r=n.getBoundingClientRect();return {x:r.x+r.width/2,y:r.y+r.height/2}})()');
  await cdp('Input.dispatchMouseEvent',{type:'mousePressed',...gutter,button:'left',clickCount:1});
  await cdp('Input.dispatchMouseEvent',{type:'mouseReleased',...gutter,button:'left',clickCount:1});
  await wait('document.querySelector("#inline-comment-body") && !document.querySelector(".selection-actions").hidden');
  await evaluate('document.querySelector("#inline-comment-body").value="保留代码评论草稿";document.querySelector("#inline-comment-body").dispatchEvent(new Event("input"));document.querySelector("#next-comment").focus()');
  await key();assert.equal(await active(),newest.id);
  await evaluate('document.querySelector("#next-comment").click()');
  assert.equal(await evaluate('document.querySelector("#inline-comment-body").value'),'保留代码评论草稿');
  await evaluate('document.querySelector(".selection-actions button[type=button]").click()');
  for (const comment of [older,otherFile,newest]) await app.store.remove(comment.id);
  await cdp('Page.reload');await wait('document.querySelector(".change-count")?.textContent === "1 处变更"');
}
